package com.example.workflowservice.enums;

/**
 * Статусы бизнес-процессов
 * Каждый тип процесса (WorkflowType) имеет свой набор допустимых статусов
 */
public enum WorkflowStatus {

    // ========== Статусы для TICKET_CREATION ==========

    /**
     * Черновик - начальное состояние заявки, ещё не отправлено
     */
    DRAFT("Черновик"),

    /**
     * Заявка отправлена на рассмотрение
     */
    SUBMITTED("Отправлена"),

    /**
     * Заявка находится на рассмотрении
     */
    IN_REVIEW("На рассмотрении"),

    /**
     * Заявка одобрена, ожидает выполнения
     */
    APPROVED("Одобрена"),

    /**
     * Заявка полностью выполнена
     */
    COMPLETED("Завершена"),

    // ========== Статусы для DOCUMENT_SIGNING ==========

    /**
     * Документ создан, но ещё не отправлен
     */
    CREATED("Создан"),

    /**
     * Документ отправлен на подпись
     */
    SENT("Отправлен"),

    /**
     * Документ находится в процессе подписания
     */
    IN_PROGRESS("В процессе"),

    /**
     * Документ успешно подписан
     */
    SIGNED("Подписан"),

    /**
     * Срок подписания документа истёк
     */
    EXPIRED("Истёк срок"),

    /**
     * Документ отклонён (не подписан)
     */
    REJECTED("Отклонён"),

    // ========== Статусы для USER_BLOCKING ==========

    /**
     * Процесс блокировки пользователя инициирован
     */
    INITIATED("Инициирована"),

    /**
     * Блокировка пользователя на рассмотрении
     */
    IN_REVIEW_STATUS("На рассмотрении"),

    /**
     * Пользователь заблокирован
     */
    BLOCKED("Заблокирован");

    // Человекопонятное название статуса
    private final String displayName;

    WorkflowStatus(String displayName) {
        this.displayName = displayName;
    }

    /**
     * Возвращает отображаемое имя статуса
     * @return название на русском языке
     */
    public String getDisplayName() {
        return displayName;
    }

    /**
     * Проверяет, является ли статус финальным (процесс завершён)
     * Финальные статусы не допускают дальнейших переходов
     *
     * @return true если статус финальный
     */
    public boolean isFinal() {
        return this == COMPLETED || this == SIGNED || this == EXPIRED ||
                this == BLOCKED || this == REJECTED;
    }
}