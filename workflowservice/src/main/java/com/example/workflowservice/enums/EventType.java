package com.example.workflowservice.enums;

/**
 * Типы событий для обмена через Kafka
 * Определяют, какое именно событие произошло в системе
 * Используются для маршрутизации и обработки сообщений
 */
public enum EventType {

    // ========== События от Ticket Service ==========

    /**
     * Заявка (тикет) была создана
     */
    TICKET_CREATED("Заявка создана"),

    /**
     * Заявка была обновлена
     */
    TICKET_UPDATED("Заявка обновлена"),

    /**
     * Заявка была удалена (soft delete)
     */
    TICKET_DELETED("Заявка удалена"),

    // ========== События от Document Service ==========

    /**
     * Документ был создан
     */
    DOCUMENT_CREATED("Документ создан"),

    /**
     * Документ отправлен на подпись
     */
    DOCUMENT_SENT("Документ отправлен"),

    /**
     * Документ успешно подписан
     */
    DOCUMENT_SIGNED("Документ подписан"),

    // ========== События от User/Auth Service ==========

    /**
     * Пользователь был создан
     */
    USER_CREATED("Пользователь создан"),

    /**
     * Поступил запрос на блокировку пользователя
     */
    USER_BLOCK_REQUESTED("Запрос на блокировку"),

    /**
     * Пользователь был разблокирован
     */
    USER_UNBLOCKED("Пользователь разблокирован"),

    // ========== События от Workflow Service ==========

    /**
     * Бизнес-процесс (воркфлоу) был создан
     */
    WORKFLOW_CREATED("Процесс создан"),

    /**
     * Статус бизнес-процесса был изменён
     */
    WORKFLOW_STATUS_CHANGED("Статус изменён"),

    /**
     * Бизнес-процесс успешно завершён
     */
    WORKFLOW_COMPLETED("Процесс завершён"),

    /**
     * Бизнес-процесс был отклонён
     */
    WORKFLOW_REJECTED("Процесс отклонён");

    // Человекопонятное описание события (для логов и отладки)
    private final String description;

    EventType(String description) {
        this.description = description;
    }

    /**
     * Возвращает описание события
     * @return текстовое описание на русском языке
     */
    public String getDescription() {
        return description;
    }
}